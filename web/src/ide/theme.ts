import { monaco } from './monaco';
import { alpha, DIFF, mix, SYNTAX } from './palette';
import { isDark, readTokens } from './tokens';

/**
 * Thèmes Monaco « tarmac-light » et « tarmac-dark » : couleurs d'interface tirées des jetons de l'app au moment
 * où le thème s'applique (ide/tokens.ts), coloration syntaxique de palette.ts.
 */

// ─── Monaco ─────────────────────────────────────────────────────────────────
const strip = (c: string) => c.slice(1);

function monacoTheme(dark: boolean): monaco.editor.IStandaloneThemeData {
  const k = readTokens(dark);
  const s = SYNTAX[dark ? 'dark' : 'light'];
  const d = DIFF[dark ? 'dark' : 'light'];
  const hover = mix(k.panel, k.fg, dark ? 0.06 : 0.04);
  const selected = mix(k.panel, k.accent, dark ? 0.2 : 0.12);
  const rule = (token: string, color: string, fontStyle?: string) => ({ token, foreground: strip(color), ...(fontStyle ? { fontStyle } : {}) });
  return {
    base: dark ? 'vs-dark' : 'vs',
    inherit: true,
    rules: [
      { token: '', foreground: strip(k.fg), background: strip(k.panel) },
      rule('comment', s.comment, 'italic'),
      rule('comment.doc', s.comment, 'italic'),
      rule('keyword', s.keyword),
      rule('keyword.flow', s.keyword),
      rule('keyword.json', s.keyword),
      rule('storage', s.keyword),
      rule('string', s.string),
      rule('string.escape', s.regexp),
      rule('string.key.json', s.attribute),
      rule('string.value.json', s.string),
      rule('number', s.number),
      rule('number.hex', s.number),
      rule('constant', s.number),
      rule('regexp', s.regexp),
      rule('type', s.type),
      rule('type.identifier', s.type),
      rule('identifier', k.fg),
      rule('variable', k.fg),
      rule('variable.predefined', s.type),
      rule('delimiter', s.delimiter),
      rule('delimiter.html', s.delimiter),
      rule('delimiter.xml', s.delimiter),
      rule('tag', s.tag),
      rule('tag.id.pug', s.tag),
      rule('metatag', s.tag),
      rule('metatag.content.html', s.string),
      rule('attribute.name', s.attribute),
      rule('attribute.value', s.string),
      rule('attribute.value.number', s.number),
      rule('attribute.value.unit', s.number),
      rule('attribute.value.hex', s.number),
      rule('key', s.attribute),
      rule('predefined', s.type),
      rule('annotation', s.tag),
      rule('emphasis', k.fg, 'italic'),
      rule('strong', k.fg, 'bold'),
      rule('keyword.md', s.keyword),
      rule('string.link', s.type),
      rule('variable.source', s.tag),
    ],
    colors: {
      foreground: k.fg,
      focusBorder: k.accent,
      'widget.shadow': dark ? '#00000066' : '#0f172a1f',
      'widget.border': k.line,
      'editor.background': k.panel,
      'editor.foreground': k.fg,
      'editorGutter.background': k.panel,
      'editorLineNumber.foreground': k.faint,
      'editorLineNumber.activeForeground': k.fg,
      'editorCursor.foreground': k.accent,
      'editor.lineHighlightBackground': hover,
      'editor.lineHighlightBorder': '#00000000',
      'editor.selectionBackground': alpha(k.accent, dark ? 0.32 : 0.2),
      'editor.inactiveSelectionBackground': alpha(k.accent, dark ? 0.18 : 0.1),
      'editor.selectionHighlightBackground': alpha(k.accent, dark ? 0.16 : 0.1),
      'editor.wordHighlightBackground': alpha(k.accent, dark ? 0.16 : 0.1),
      'editor.wordHighlightStrongBackground': alpha(k.accent, dark ? 0.24 : 0.16),
      'editor.findMatchBackground': dark ? '#f59e0b66' : '#f59e0b55',
      'editor.findMatchHighlightBackground': dark ? '#f59e0b33' : '#f59e0b2a',
      'editor.findRangeHighlightBackground': alpha(k.accent, 0.08),
      'editor.rangeHighlightBackground': alpha(k.accent, dark ? 0.12 : 0.07),
      'editor.hoverHighlightBackground': alpha(k.accent, 0.1),
      'editorLink.activeForeground': k.accent,
      'editorWhitespace.foreground': alpha(k.faint, 0.5),
      'editorIndentGuide.background1': k.line,
      'editorIndentGuide.activeBackground1': mix(k.line, k.faint, 0.6),
      'editorRuler.foreground': k.line,
      'editorBracketMatch.background': alpha(k.accent, 0.14),
      'editorBracketMatch.border': alpha(k.accent, 0.5),
      'editorBracketHighlight.foreground1': s.brackets[0],
      'editorBracketHighlight.foreground2': s.brackets[1],
      'editorBracketHighlight.foreground3': s.brackets[2],
      'editorBracketHighlight.foreground4': s.brackets[0],
      'editorBracketHighlight.foreground5': s.brackets[1],
      'editorBracketHighlight.foreground6': s.brackets[2],
      'editorStickyScroll.background': k.panel,
      'editorStickyScrollHover.background': hover,
      'editorStickyScroll.border': k.line,
      'editorStickyScroll.shadow': '#00000000',
      'editorOverviewRuler.border': '#00000000',
      'editorOverviewRuler.background': k.panel,
      'scrollbar.shadow': '#00000000',
      'scrollbarSlider.background': alpha(k.faint, 0.28),
      'scrollbarSlider.hoverBackground': alpha(k.faint, 0.45),
      'scrollbarSlider.activeBackground': alpha(k.faint, 0.6),
      'minimap.background': k.panel,
      'minimapSlider.background': alpha(k.faint, 0.16),
      'minimapSlider.hoverBackground': alpha(k.faint, 0.26),
      'minimapSlider.activeBackground': alpha(k.faint, 0.36),
      'editorWidget.background': k.panel,
      'editorWidget.foreground': k.fg,
      'editorWidget.border': k.line,
      'editorWidget.resizeBorder': k.line,
      'editorHoverWidget.background': k.panel,
      'editorHoverWidget.border': k.line,
      'editorHoverWidget.foreground': k.fg,
      'editorHoverWidget.statusBarBackground': k.panel2,
      'editorSuggestWidget.background': k.panel,
      'editorSuggestWidget.border': k.line,
      'editorSuggestWidget.foreground': k.fg,
      'editorSuggestWidget.selectedBackground': selected,
      'editorSuggestWidget.selectedForeground': k.fg,
      'editorSuggestWidget.highlightForeground': k.accent,
      'editorSuggestWidget.focusHighlightForeground': k.accent,
      'list.hoverBackground': hover,
      'list.activeSelectionBackground': selected,
      'list.activeSelectionForeground': k.fg,
      'list.inactiveSelectionBackground': selected,
      'list.focusBackground': selected,
      'list.highlightForeground': k.accent,
      'list.focusHighlightForeground': k.accent,
      'input.background': k.panel2,
      'input.foreground': k.fg,
      'input.border': k.line,
      'input.placeholderForeground': k.faint,
      'inputOption.activeBorder': k.accent,
      'inputOption.activeBackground': alpha(k.accent, 0.16),
      'inputOption.activeForeground': k.fg,
      'button.background': k.accent,
      'button.foreground': k.accentFg,
      'icon.foreground': k.muted,
      'toolbar.hoverBackground': hover,
      'sash.hoverBorder': k.accent,
      'menu.background': k.panel,
      'menu.foreground': k.fg,
      'menu.border': k.line,
      'menu.selectionBackground': k.accent,
      'menu.selectionForeground': k.accentFg,
      'menu.separatorBackground': k.line,
      'quickInput.background': k.panel,
      'quickInput.foreground': k.fg,
      'quickInputList.focusBackground': selected,
      'quickInputList.focusForeground': k.fg,
      'pickerGroup.foreground': k.accent,
      'pickerGroup.border': k.line,
      'keybindingLabel.background': k.panel2,
      'keybindingLabel.foreground': k.muted,
      'keybindingLabel.border': k.line,
      'keybindingLabel.bottomBorder': k.line,
      'peekView.border': k.accent,
      'peekViewEditor.background': k.panel,
      'peekViewResult.background': k.bg,
      'peekViewTitle.background': k.bg,
      'diffEditor.insertedTextBackground': alpha(d.add, dark ? 0.24 : 0.2),
      'diffEditor.removedTextBackground': alpha(d.del, dark ? 0.24 : 0.18),
      'diffEditor.insertedLineBackground': alpha(d.add, dark ? 0.1 : 0.08),
      'diffEditor.removedLineBackground': alpha(d.del, dark ? 0.1 : 0.07),
      'diffEditorGutter.insertedLineBackground': alpha(d.add, dark ? 0.16 : 0.14),
      'diffEditorGutter.removedLineBackground': alpha(d.del, dark ? 0.16 : 0.12),
      'diffEditorOverview.insertedForeground': alpha(d.add, 0.6),
      'diffEditorOverview.removedForeground': alpha(d.del, 0.6),
      'diffEditor.diagonalFill': k.line,
      'diffEditor.border': k.line,
      'diffEditor.unchangedRegionBackground': k.bg,
      'diffEditor.unchangedRegionForeground': k.muted,
      'diffEditor.unchangedCodeBackground': alpha(k.faint, 0.08),
      'diffEditor.move.border': alpha(k.faint, 0.5),
    },
  };
}

/** Nom du thème Monaco pour le mode courant, défini (ou redéfini) à partir des jetons à l'instant présent. */
export function applyMonacoTheme(dark = isDark()) {
  const name = dark ? 'tarmac-dark' : 'tarmac-light';
  monaco.editor.defineTheme(name, monacoTheme(dark));
  monaco.editor.setTheme(name);
  return name;
}
